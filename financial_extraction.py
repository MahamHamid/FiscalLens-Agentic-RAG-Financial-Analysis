"""
financial_extraction.py

Same extraction logic developed and validated in Testing_final_v4.ipynb,
refactored into plain importable functions so the live Gradio app can run
it on upload instead of requiring a separate manual notebook pass.

This does NOT replace the notebook — the notebook remains useful for
bulk/offline processing or debugging a problematic PDF page-by-page.
This module is for the app to call automatically per uploaded PDF.
"""

import os
import re
import time
import json

import pdfplumber
from langchain_groq import ChatGroq
from langchain_core.messages import HumanMessage, SystemMessage


# -----------------------------------------------------------------------------
# Page-finding logic (identical to the notebook's validated version — do not
# simplify this; the dual-signal check is what prevents segment-note and
# percentage-table false positives found during earlier testing).
# -----------------------------------------------------------------------------
STATEMENT_SIGNATURE_PHRASES = {
    "Income Statement": [
        "COST OF SALES", "COST OF REVENUE", "GROSS MARGIN", "GROSS PROFIT",
        "OPERATING EXPENSES", "NET INCOME", "EARNINGS PER SHARE",
        "PROVISION FOR INCOME TAXES", "RESEARCH AND DEVELOPMENT",
    ],
    "Balance Sheet": [
        "TOTAL ASSETS", "TOTAL LIABILITIES", "SHAREHOLDERS", "STOCKHOLDERS",
        "CASH AND CASH EQUIVALENTS", "ACCOUNTS PAYABLE", "TOTAL CURRENT ASSETS",
    ],
    "Cash Flow Statement": [
        "OPERATING ACTIVITIES", "INVESTING ACTIVITIES", "FINANCING ACTIVITIES",
        "CASH GENERATED BY OPERATING ACTIVITIES", "DEPRECIATION AND AMORTIZATION",
    ],
}

STATEMENT_HEADINGS = {
    "Income Statement": ["CONSOLIDATED STATEMENTS OF OPERATIONS", "STATEMENTS OF INCOME"],
    "Balance Sheet": ["CONSOLIDATED BALANCE SHEET"],
    "Cash Flow Statement": ["CONSOLIDATED STATEMENTS OF CASH FLOWS"],
}

DISQUALIFYING_PHRASES = [
    "REPORTABLE SEGMENT", "GEOGRAPHIC", "SEGMENT INFORMATION",
    "LONG-LIVED ASSETS", "RECONCILIATION",
]

FINANCIAL_NUMBER_PATTERN = re.compile(r"\b\d{1,3}(?:,\d{3})+\b")
MIN_FINANCIAL_NUMBERS = 5


def find_statement_pages(pdf_path):
    candidates = {k: [] for k in STATEMENT_HEADINGS}

    with pdfplumber.open(pdf_path) as pdf:
        for i, page in enumerate(pdf.pages, start=1):
            text = page.extract_text() or ""
            text_upper = text.upper()

            for stmt_name, needles in STATEMENT_HEADINGS.items():
                if not any(n in text_upper for n in needles):
                    continue
                if any(dq in text_upper for dq in DISQUALIFYING_PHRASES):
                    continue

                financial_number_count = len(FINANCIAL_NUMBER_PATTERN.findall(text))
                if financial_number_count < MIN_FINANCIAL_NUMBERS:
                    continue

                signature_score = sum(
                    1 for phrase in STATEMENT_SIGNATURE_PHRASES[stmt_name]
                    if phrase in text_upper
                )
                candidates[stmt_name].append((i, signature_score, financial_number_count))

    best_pages = {}
    for stmt_name, cands in candidates.items():
        if not cands:
            continue
        best_page, best_score, best_numcount = max(cands, key=lambda x: (x[1], x[2]))
        best_pages[stmt_name] = best_page

    return best_pages


def extract_statement_text(pdf_path, page_number):
    with pdfplumber.open(pdf_path) as pdf:
        page = pdf.pages[page_number - 1]
        return page.extract_text(layout=True) or ""


EXTRACTION_SYSTEM_PROMPT = """You are a precise financial data extraction engine.

You will be given raw text extracted from ONE page of a company's financial
statements. The text preserves column alignment using spaces, so numbers
may be spaced out unevenly — read the years IN LINE with the numbers below
them.

Your job: convert every reported line item into a flat JSON array of
objects with EXACTLY this schema:

[
  {
    "company": "<company name given to you>",
    "statement": "<Income Statement | Balance Sheet | Cash Flow Statement>",
    "section": "<the sub-heading this line falls under — see rules below>",
    "metric": "<line item name, e.g. 'Total net sales', 'Net income'>",
    "year": <4-digit integer>,
    "value": <number, no $ signs or commas>,
    "unit": "<see unit rules below>"
  },
  ...
]

Be CONCISE: no extra whitespace, no explanatory text, compact JSON only.

SECTION RULES (critical for disambiguation):
- Every line item MUST include the sub-heading it appears under, exactly
  as printed on the page. The SAME metric name can appear more than once
  under different sections with different values — you MUST capture the
  section so these rows remain distinguishable.
- If a page has no clear sub-heading structure, use "General".

UNIT RULES (critical — do not mislabel share counts as currency):
- Dollar/currency figures -> unit: "USD millions" (or the actual reported unit).
- Per-share figures -> unit: "USD per share".
- Share COUNTS -> unit: "shares in thousands" (or "shares in millions").
  NEVER label a share count as "USD millions".
- Percentages -> unit: "percent".

CRITICAL RULES:
- Do NOT invent, estimate, or calculate any number. Only report figures
  that literally appear in the text.
- Numbers in parentheses, e.g. (321), are NEGATIVE: output -321.
- Every row needs company, statement, section, metric, year, value, unit.
- Return ONLY the JSON array. No markdown fences, no commentary, no preamble.
"""


def parse_json_with_recovery(raw_output):
    try:
        return json.loads(raw_output), False
    except json.JSONDecodeError:
        pass

    recovered = []
    depth = 0
    start = None
    for idx, ch in enumerate(raw_output):
        if ch == "{":
            if depth == 0:
                start = idx
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0 and start is not None:
                chunk = raw_output[start:idx + 1]
                try:
                    recovered.append(json.loads(chunk))
                except json.JSONDecodeError:
                    pass
                start = None
    return recovered, True


def extract_financial_data_from_pdf(pdf_path, company_name, llm=None, max_retries=3):
    """
    Runs the full extraction pipeline on ONE PDF and returns a list of row
    dicts (same schema as financial_data.csv), or an empty list if nothing
    could be reliably extracted (e.g. not a financial statement / no
    qualifying pages found). Never raises for "no data found" — only for
    genuine unexpected errors, which the caller should catch anyway.
    """
    if llm is None:
        llm_model_name = os.getenv("GROQ_MODEL", "openai/gpt-oss-120b")
        llm = ChatGroq(model=llm_model_name, temperature=0, max_tokens=6000)

    found_pages = find_statement_pages(pdf_path)
    if not found_pages:
        return []  # not a recognizable financial-statement document — RAG can still index it as text

    all_rows = []

    for stmt_name, page_num in found_pages.items():
        raw_text = extract_statement_text(pdf_path, page_num)
        if not raw_text.strip():
            continue

        user_prompt = f"""Company: {company_name}
Statement type: {stmt_name}

Raw extracted text (column-aligned with spaces):

{raw_text}

Convert this into the JSON array described in your instructions."""

        raw_output = None
        for attempt in range(max_retries):
            try:
                response = llm.invoke([
                    SystemMessage(content=EXTRACTION_SYSTEM_PROMPT),
                    HumanMessage(content=user_prompt),
                ])
                raw_output = response.content.strip()
                break
            except Exception as e:
                if "rate_limit" in str(e).lower() or "429" in str(e) or "413" in str(e):
                    wait_time = 10 * (attempt + 1)
                    print(f"[financial_extraction] Rate limit hit, waiting {wait_time}s (attempt {attempt+1}/{max_retries})")
                    time.sleep(wait_time)
                else:
                    print(f"[financial_extraction] Non-rate-limit error on {stmt_name}: {e}")
                    break

        if raw_output is None:
            continue  # this statement failed — skip it, don't fail the whole PDF

        raw_output = re.sub(r"^```(json)?", "", raw_output).strip()
        raw_output = re.sub(r"```$", "", raw_output).strip()

        rows, _was_truncated = parse_json_with_recovery(raw_output)
        for row in rows:
            row["source_file"] = os.path.basename(str(pdf_path))
        all_rows.extend(rows)

        # Only pause if we actually had to retry (i.e. we were close to a
        # rate limit) — no fixed delay when everything succeeded on the
        # first try, which is the common case and was slowing every
        # upload down unnecessarily.
        if attempt > 0:
            time.sleep(2)

    return all_rows